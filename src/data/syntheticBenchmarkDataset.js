/**
 * Load all 135 benchmark cases into active application state (Tree Registry & Validation DB)
 * @param {object} state Application state object
 * @returns {number} Number of loaded records
 */
export function loadBenchmarkIntoApp(state) {
  if (!state) return 0;
  
  state.registry = state.registry || { trees: [] };
  state.validation = state.validation || { records: [] };

  const convertedTrees = SYNTHETIC_BENCHMARK_CASES.map(c => ({
    id: c.caseId,
    species: c.genus,
    height: c.estHeight,
    dbh: c.estDbh,
    agb: c.estAgb,
    co2: c.estCo2,
    density: c.rho,
    confidence: c.conf,
    confidenceScorePct: Math.round(c.conf * 100),
    lat: c.lat,
    lon: c.lon,
    timestamp: new Date(Date.now() - Math.floor(Math.random() * 86400000 * 14)).toISOString(),
    distance: c.distance,
    distanceErr: 0.15,
    heightErr: Math.abs(c.heightErr),
    dbhErr: Math.abs(c.dbhErr),
    agbErr: Math.round(c.estAgb * 0.05),
    co2Err: Math.round(c.estCo2 * 0.05),
    sensorStability: c.stability,
    lightingQuality: c.lighting,
    calibrationVersion: "2.4.0-BENCHMARK",
    hfov: 60.0,
    vfov: 45.0,
    deviceModel: "Standard Mobile Camera"
  }));

  const convertedValRecords = SYNTHETIC_BENCHMARK_CASES.map(c => ({
    id: c.caseId,
    timestamp: new Date().toISOString(),
    groundTruth: {
      height: c.gtHeight,
      dbh: c.gtDbh
    },
    application: {
      height: c.estHeight,
      dbh: c.estDbh,
      distance: c.distance
    },
    sensors: {
      rawPitch: c.thetaBaseDeg,
      filteredPitch: c.thetaBaseDeg
    },
    calibration: {
      left: 120,
      right: 360,
      top: 80,
      base: 420,
      hfov: 60.0,
      vfov: 45.0,
      cameraHeight: 1.6
    },
    caliperDrag: {
      left: 120,
      right: 360
    },
    terrain: {
      slopeAngle: 0.0
    },
    device: {
      manufacturer: "Synthetic Benchmark Engine",
      model: "Standard Mobile Camera",
      screenResolution: "1920x1080",
      osVersion: "Simulated",
      browser: "Porta-TLS Engine"
    },
    expedition: {
      projectName: "PORTA-TLS GLOBAL FIELD VALIDATION",
      siteName: c.site,
      operatorName: "Scientific Benchmark Team",
      weather: c.lighting,
      startTime: new Date().toISOString(),
      endTime: null,
      scanCount: 135
    }
  }));

  state.registry.trees = convertedTrees;
  state.validation.records = convertedValRecords;

  try {
    localStorage.setItem("qt_tls_inventory", JSON.stringify(convertedTrees));
    localStorage.setItem("portatls_validation_records", JSON.stringify(convertedValRecords));
  } catch (e) {
    console.warn("Could not save to localStorage", e);
  }

  return convertedTrees.length;
}
