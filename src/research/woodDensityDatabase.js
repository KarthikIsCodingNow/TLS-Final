/**
 * Find species database record by common name, scientific name, or substring
 * @param {string} searchName
 * @returns {object}
 */
export function getSpeciesData(searchName) {
  if (!searchName) {
    return {
      commonName: 'Generic Hardwood',
      scientificName: 'Plantae Incertae Sedis',
      densityGcm3: 0.65,
      typicalHeightM: 18.0,
      typicalDbhCm: 45.0,
      region: 'Andhra Pradesh',
      biome: 'Tropical Deciduous',
      growthRate: 'Moderate',
      family: 'Unknown',
      carbonFactor: 0.48
    };
  }

  const query = searchName.toLowerCase().trim();

  const found = SPECIES_WOOD_DATABASE.find(s => 
    s.commonName.toLowerCase().includes(query) ||
    s.englishName?.toLowerCase().includes(query) ||
    s.teluguName?.toLowerCase().includes(query) ||
    s.scientificName.toLowerCase().includes(query) ||
    query.includes(s.englishName?.toLowerCase() || '') ||
    query.includes(s.scientificName.toLowerCase())
  );

  return found || {
    commonName: searchName,
    scientificName: 'Plantae Incertae Sedis',
    densityGcm3: 0.65,
    typicalHeightM: 18.0,
    typicalDbhCm: 45.0,
    region: 'Andhra Pradesh',
    biome: 'Tropical Deciduous',
    growthRate: 'Moderate',
    family: 'Unknown',
    carbonFactor: 0.48
  };
}
